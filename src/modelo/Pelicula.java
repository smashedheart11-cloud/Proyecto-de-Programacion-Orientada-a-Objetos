package modelo;

public class Pelicula {
    int idPelicula;
    String titulo;
    String genero;
    String clasificacion;
    String idioma;

    public Pelicula (int idPelicula, String titulo, String genero, String clasificacion, String idioma){
        this.idPelicula=idPelicula;
        this.titulo=titulo;
        this.genero=genero;
        this.clasificacion=clasificacion;
        this.idioma=idioma;
    }


}
